"""
Bake the night sky's shader for the GPU sky (widgets/sky_gpu.py).

    python tools/bake_sky_shader.py --qsb PATH/TO/qsb.exe
    python tools/bake_sky_shader.py --qsb PATH/TO/qsb.exe --shader disc

Reads stream_denoiser/gui/assets/sky/sky.frag and writes, next to it,
sky.frag.qsb (Qt's shader pack: the SPIR-V compiled for GLSL, HLSL and
MSL) and sky.qml (a ShaderEffect with one property per uniform, the way
it maps them, and for each sampler a hidden Image it reads, loaded from
an image provider: see sky_gpu.SkyView). Both are committed; run this
after editing sky.frag. --shader disc bakes the Home scene's disc
(disc.frag -> disc.frag.qsb) instead; its QML is HomeDial.qml, written
by hand, so no QML is generated for it.

qsb ships with Qt (not with PyQt6): with pip, PySide6-Addons has it as
PySide6/qsb.exe, which needs the Qt DLLs of PySide6-Essentials beside it.
Use the same Qt minor version as PyQt6's, so the pack's format matches.
--check only compares the QML with the shader (no qsb needed).

On Windows the pack's HLSL is then replaced by its compiled bytecode
(DXBC, with the d3dcompiler_47.dll that PyQt6 ships): Direct3D would
otherwise compile the shader when the sky first shows, freezing the
window for about a second. (qsb's own --fxc needs the Windows SDK.)
"""
import argparse
import ctypes
import re
import struct
import subprocess
import sys
import zlib
from pathlib import Path

SKY = (Path(__file__).resolve().parent.parent
       / "stream_denoiser" / "gui" / "assets" / "sky")
QML_TYPES = {"float": "real", "vec2": "size", "vec4": "vector4d"}


def uniforms(frag: str):
    """(type, name) of each uniform in the shader's block, in order."""
    block = re.search(r"uniform\s+buf\s*\{(.*?)\};", frag, re.S).group(1)
    block = re.sub(r"//[^\n]*", "", block)
    out = []
    for decl in block.split(";"):
        decl = decl.strip()
        if not decl:
            continue
        kind, name = decl.split()
        if not name.startswith("qt_"):
            out.append((kind, name))
    return out


def samplers(frag: str):
    """Names of the shader's sampler2D uniforms, in order."""
    return re.findall(r"uniform\s+sampler2D\s+(\w+)\s*;", frag)


def qml(frag: str) -> str:
    lines = [
        "// Generated by tools/bake_sky_shader.py from sky.frag: one",
        "// property per uniform (widgets/sky_gpu.py sets them each frame).",
        "import QtQuick",
        "",
        "ShaderEffect {",
    ]
    for kind, name in uniforms(frag):
        if name == "size":
            lines.append("    property size size: Qt.size(width, height)")
        else:
            lines.append(f"    property {QML_TYPES[kind]} {name}")
    for name in samplers(frag):
        lines += [f'    property string {name}Source: "image://sky/{name}/0"',
                  f"    property var {name}: {name}Image",
                  "    Image {",
                  f"        id: {name}Image",
                  "        visible: false",
                  "        cache: false",
                  "        smooth: false",
                  f"        source: parent.{name}Source",
                  "    }"]
    lines += ['    fragmentShader: "sky.frag.qsb"', "}", ""]
    return "\n".join(lines)


# QShaderKey sources (qshader.h) and the HLSL version qsb writes.
HLSL, DXBC = 2, 3
HLSL_VERSION = 50


def _d3dcompile(hlsl: bytes) -> bytes:
    """ps_5_0 bytecode of `hlsl` (entry point main)."""
    import PyQt6
    dll = ctypes.WinDLL(str(Path(PyQt6.__file__).parent / "Qt6" / "bin"
                            / "d3dcompiler_47.dll"))
    blob, errors = ctypes.c_void_p(), ctypes.c_void_p()
    compile_ = dll.D3DCompile
    compile_.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p,
                         ctypes.c_void_p, ctypes.c_void_p, ctypes.c_char_p,
                         ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                         ctypes.POINTER(ctypes.c_void_p),
                         ctypes.POINTER(ctypes.c_void_p)]
    hr = compile_(hlsl, len(hlsl), b"shader.frag", None, None, b"main",
                  b"ps_5_0", 0, 0, ctypes.byref(blob), ctypes.byref(errors))
    if hr != 0:
        message = _blob(errors).decode(errors="replace") if errors else ""
        raise RuntimeError(f"D3DCompile failed ({hr & 0xFFFFFFFF:#x}):\n"
                           f"{message}")
    return _blob(blob)


def _blob(blob) -> bytes:
    """An ID3DBlob's bytes (GetBufferPointer, GetBufferSize: vtable
    slots 3 and 4)."""
    vtable = ctypes.cast(ctypes.cast(blob, ctypes.POINTER(ctypes.c_void_p))[0],
                         ctypes.POINTER(ctypes.c_void_p))
    pointer = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(
        vtable[3])(blob)
    size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(
        vtable[4])(blob)
    return ctypes.string_at(pointer, size)


def with_dxbc(pack: bytes, hlsl: bytes) -> bytes:
    """The shader pack with its HLSL entry swapped for DXBC bytecode.

    A pack is qCompress'd (a big-endian size, then zlib) QDataStream;
    each shader in it is a key (source, version, flags, variant: int32s)
    and then the code and entry point (QByteArrays: an int32 length and
    the bytes). Found by the HLSL bytes themselves, so the rest of the
    stream (the reflection data) need not be parsed. The tables that
    follow the shaders are keyed the same way (the native resource
    binding map: which register each binding uses), so every HLSL key
    in the stream becomes the DXBC one; without its map a texture binds
    to the wrong register and reads nothing.
    """
    data = zlib.decompress(pack[4:])
    key = struct.pack(">4i", HLSL, HLSL_VERSION, 0, 0)
    entry = key + struct.pack(">i", len(hlsl)) + hlsl
    at = data.find(entry)
    if at < 0 or data.find(entry, at + 1) >= 0:
        raise RuntimeError("the pack's HLSL entry was not found once")
    code = _d3dcompile(hlsl)
    dxbc = struct.pack(">4i", DXBC, HLSL_VERSION, 0, 0)
    head = data[:at]
    tail = data[at + len(entry):]
    if key in head:
        raise RuntimeError("an HLSL key before the shaders: not a pack "
                           "this understands")
    tables = tail.count(key)
    if tables > 3:      # binding map, sampler map, native shader info
        raise RuntimeError(f"{tables} HLSL keys after the shaders")
    data = (head + dxbc + struct.pack(">i", len(code)) + code
            + tail.replace(key, dxbc))
    return struct.pack(">I", len(data)) + zlib.compress(data, 9)


def bake(qsb: str, name: str) -> Path:
    """NAME.frag -> NAME.frag.qsb (with DXBC on Windows)."""
    pack = SKY / f"{name}.frag.qsb"
    subprocess.run([qsb, "--glsl", "100 es,120,150", "--hlsl", "50",
                    "--msl", "12", "-o", str(pack), str(SKY / f"{name}.frag")],
                   check=True)
    if sys.platform == "win32":
        hlsl = SKY / f"{name}.hlsl.tmp"
        subprocess.run([qsb, "-x", f"hlsl,{HLSL_VERSION}", "-o",
                        str(hlsl), str(pack)], check=True)
        try:
            pack.write_bytes(with_dxbc(pack.read_bytes(), hlsl.read_bytes()))
        finally:
            hlsl.unlink()
        print("  HLSL compiled to DXBC")
    else:
        print("  (not on Windows: the pack keeps HLSL source, which "
              "Direct3D compiles when the shader first shows)")
    return pack


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--qsb", help="Qt's qsb executable")
    parser.add_argument("--shader", default="sky",
                        help="which shader: sky (default) or disc")
    parser.add_argument("--check", action="store_true",
                        help="only check that sky.qml matches sky.frag")
    args = parser.parse_args()
    frag = (SKY / "sky.frag").read_text(encoding="utf-8")
    text = qml(frag)
    if args.check:
        if (SKY / "sky.qml").read_text(encoding="utf-8") != text:
            print("sky.qml is out of date: run tools/bake_sky_shader.py")
            return 1
        return 0
    if not args.qsb:
        parser.error("--qsb is required to bake")
    if args.shader != "sky":
        print(f"baked {bake(args.qsb, args.shader)}")
        return 0
    (SKY / "sky.qml").write_text(text, encoding="utf-8", newline="\n")
    pack = bake(args.qsb, "sky")
    print(f"baked {pack} and {SKY / 'sky.qml'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
